const TYPO_PAIRS = TYPO_FIXES.filter(([a, b]) => a !== b);

function applyTypoFixes(s) {
  let out = s;
  for (const [bad, good] of TYPO_PAIRS) {
    if (out.includes(bad)) out = out.split(bad).join(good);
  }
  return out;
}

// Match month markers anywhere in text.
const MONTH_TOKENS = [
  "正月","一月","二月","三月","四月","五月","六月","七月","八月","九月","十月","十一月","十二月",
  "闰正月","闰一月","闰二月","闰三月","闰四月","闰五月","闰六月","闰七月","闰八月","闰九月","闰十月","闰十一月","闰十二月",
  "閏正月","閏一月","閏二月","閏三月","閏四月","閏五月","閏六月","閏七月","閏八月","閏九月","閏十月","閏十一月","閏十二月",
  "是年","是月","是岁","是冬","是春","是夏","是秋",
];
// Sort longer tokens first so e.g. "十二月" is matched before "二月".
MONTH_TOKENS.sort((a, b) => b.length - a.length);
const MONTH_RE = new RegExp("(" + MONTH_TOKENS.join("|") + ")", "g");

// Split a 大事记 chunk into [{month, text}, ...].
// If no month token appears, returns [{month: "", text: whole}].
function splitByMonth(s) {
  const out = [];
  let lastIdx = 0;
  let lastMonth = "";
  let m;
  MONTH_RE.lastIndex = 0;
  while ((m = MONTH_RE.exec(s))) {
    if (m.index > lastIdx) {
      const chunk = s.slice(lastIdx, m.index).trim();
      if (chunk) out.push({ month: lastMonth, text: chunk });
    } else if (lastMonth && out.length === 0) {
      // text starts with first month token — flushed below
    }
    lastMonth = m[1];
    lastIdx = m.index + m[1].length;
  }
  const tail = s.slice(lastIdx).trim();
  if (tail) out.push({ month: lastMonth, text: tail });
  if (out.length === 0 && s.trim()) out.push({ month: "", text: s.trim() });
  return out;
}

// Within a month chunk, split by 。 and yield one event per sentence.
function splitSentences(text) {
  return text
    .split(/。+/)
    .map((s) => s.trim())
    .filter(Boolean);
}

// Pull all <tr>...</tr> from the file (regex is fine — MinerU output is flat).
function extractRows(md) {
  const rows = [];
  const trRe = /<tr>([\s\S]*?)<\/tr>/g;
  let m;
  while ((m = trRe.exec(md))) {
    const cellRe = /<td[^>]*>([\s\S]*?)<\/td>/g;
    const cells = [];
    let c;
    while ((c = cellRe.exec(m[1]))) cells.push(clean(c[1]));
    if (cells.length) rows.push(cells);
  }
  return rows;
}

// Cells we want to ignore when picking the 大事记 column.
const HIJRI_RE = /^[（()]?\d{2,4}[）)]?(?:[（()]?\d{2,4}[）)]?)*$/; // 回历 like "(750)751"
const GANZHI = "甲乙丙丁戊己庚辛壬癸";
const ZHI = "子丑寅卯辰巳午未申酉戌亥";
function isGanzhi(s) {
  return s.length === 2 && GANZHI.includes(s[0]) && ZHI.includes(s[1]);
}
function isHeaderToken(s) {
  return ["公元","回历","回曆","干支","千支","于支","元","明","清","南明","后金","夏","宋","周","天完","大汉","大江","大事記","大事记","大寓記","大事註","大 事 記","大 事 记","大 寓 記","大 事 紀","大 事 記","大 事 起","大,事 記"].includes(s) ||
    /^大\s*事/.test(s);
}

// Strip leading punctuation noise (caused by OCR).
function stripLeadingPunct(s) {
  return s.replace(/^[，,、；;：:。.]+/, "").trim();
}
function tidyText(s) {
  return s.replace(/[，,]{2,}/g, "，").replace(/\s+/g, "");
}

function parse() {
  if (!fs.existsSync(SRC)) {
    console.error("MinerU markdown not found:", SRC);
    process.exit(1);
  }
  const md = fs.readFileSync(SRC, "utf8");
  const rows = extractRows(md);

  const out = [];
  out.push("# 明代大事年表（MinerU OCR 自动整理版本）");
  out.push("# 来源: donotpack/database/MinerU_markdown_大事年表_2050501523587526656.md");
  out.push("# 格式: 公元YYYY年（<年号><N>年）[月份，]<事件>。");
  out.push("");

  let pendingYear = null;
  let lastYear = null;
  let lastMonth = ""; // month context inherited from the previous rowspan row
  const stats = { rows: 0, events: 0, skipped: 0, overridden: 0 };
  const seenOverrides = new Set(); // emit each override only once

  for (const cells of rows) {
    // Header row: skip but reset month context.
    if (cells.some(isHeaderToken) && !cells.some((c) => /^\d{4}$/.test(c))) {
      lastMonth = "";
      continue;
    }

    // Pull year (or inherit from rowspan continuation).
    let year = null;
    for (const c of cells) {
      if (/^\d{4}$/.test(c) && +c >= 1300 && +c <= 1700) { year = +c; lastMonth = ""; break; }
    }
    if (!year && pendingYear) year = pendingYear;
    if (!year) continue;
    pendingYear = year;
    lastYear = year;

    // If this year has a hand-transcribed override, use it instead of the
    // OCR'd cells. Emit once, then skip all rows for that year.
    if (OVERRIDES[year]) {
      if (!seenOverrides.has(year)) {
        seenOverrides.add(year);
        const info = reignInfo(year);
        for (const [month, text] of OVERRIDES[year]) {
          for (const sent of splitSentences(text)) {
            const desc = month ? `${month}，${sent}` : sent;
            out.push(`公元${year}年（${info.reign}${info.reignYearText}年）${desc}。`);
            stats.events++;
          }
        }
        out.push("");
        stats.overridden++;
      }
      continue;
    }

    // Classify cells. Discard 回历 / 干支 / pure-number (dynasty year) / header
    // tokens. Identify month-only cells. Anything else is candidate content.
    let monthCellOnly = "";
    let recordCell = "";
    let recordLen = 0;
    for (const c of cells) {
      if (!c) continue;
      if (c === String(year)) continue;
      if (/^\d+$/.test(c)) continue;
      if (HIJRI_RE.test(c)) continue;
      if (isGanzhi(c)) continue;
      if (isHeaderToken(c)) continue;
      // Pure month token cell (rowspan-row first column).
      if (MONTH_TOKENS.includes(c)) { monthCellOnly = c; continue; }
      // OCR-merged month cell like "三五月" / "正五月" / "四五月" — chars are
      // all month-related. Extract the FIRST month-token-shaped substring.
      if (c.length <= 6 && /^[正一二三四五六七八九十闰閏是月年岁]+$/.test(c)) {
        // Try to parse out a leading month token
        for (const tok of MONTH_TOKENS) {
          if (c.startsWith(tok)) { monthCellOnly = tok; break; }
        }
        if (!monthCellOnly) {
          // Patterns like "三五月" → first digit + 月
          const m2 = c.match(/^([正一二三四五六七八九十]{1,3})/);
          if (m2) {
            const first = m2[1][0] === "正" ? "正" : m2[1][0];
            const cand = first + "月";
            if (MONTH_TOKENS.includes(cand)) monthCellOnly = cand;
          }
        }
        continue;
      }
      MONTH_RE.lastIndex = 0;
      const hasSignal = MONTH_RE.test(c) || c.includes("。") || c.length > 8;
      MONTH_RE.lastIndex = 0;
      if (hasSignal && c.length > recordLen) {
        recordCell = c;
        recordLen = c.length;
      }
    }

    if (!recordCell) { stats.skipped++; continue; }

    // Detect "concatenated month list" pattern: cell starts with ≥2 month tokens
    // run together (no separator), then events. We can't map events to months,
    // but we can extract the month list as informational metadata and emit a
    // synthetic entry telling the reader which months the original PDF covered.
    // We then strip the month-list prefix so it doesn't pollute the events.
    let leadingMonths = "";
    {
      // Greedy: take any leading run of [Chinese digits + 月年岁是闰] chars.
      // This catches OCR-mangled lists like "正月三六七月八十二月是年" where
      // separators got lost.
      const lead = recordCell.match(/^[正一二三四五六七八九十闰閏是月年岁]+/);
      if (lead && lead[0].length >= 4 && lead[0].length < recordCell.length) {
        // Walk the leading run and pull out individual months.
        const run = lead[0];
        const found = [];
        let i = 0;
        while (i < run.length) {
          // Try multi-char tokens first (是年, 是岁, 闰X月, 十一月, 十二月)
          let matched = "";
          for (const tok of MONTH_TOKENS) {
            if (run.startsWith(tok, i)) { matched = tok; break; }
          }
          if (matched) { found.push(matched); i += matched.length; continue; }
          // Single Chinese digit followed by 月 elsewhere → assume that digit + 月
          const ch = run[i];
          if ("正一二三四五六七八九十".includes(ch)) {
            const cand = ch === "正" ? "正月" : ch + "月";
            if (MONTH_TOKENS.includes(cand)) found.push(cand);
            i++;
            continue;
          }
          i++;
        }
        if (found.length >= 2) {
          leadingMonths = [...new Set(found)].join("、");
          recordCell = recordCell.slice(lead[0].length);
        }
      }
    }
    // attributes the events to that month. Otherwise, if the content cell
    // doesn't start with a month token but a previous rowspan row had one,
    // inherit it. Either way, splitByMonth handles the rest.
    let working = recordCell;
    if (monthCellOnly) {
      lastMonth = monthCellOnly;
      working = monthCellOnly + working;
    } else if (lastMonth) {
      MONTH_RE.lastIndex = 0;
      // Only inherit if the content doesn't already start with its own month.
      const startsWithMonth = MONTH_TOKENS.some((m) => working.startsWith(m));
      if (!startsWithMonth) working = lastMonth + working;
    }

    stats.rows++;
    const info = reignInfo(year);
    // Emit the original-月份 synopsis as the first entry so timeline readers
    // know which months the PDF actually covered, even though we can't map
    // individual events to them.
    if (leadingMonths) {
      out.push(`公元${year}年（${info.reign}${info.reignYearText}年）是年，本年事件原书分见：${leadingMonths}。`);
      stats.events++;
    }
    // When the leading month list was stripped, events have no month context;
    // default each to 是年 (per-row, doesn't pollute lastMonth across rows).
    const fallbackMonth = leadingMonths ? "是年" : "";
    const monthChunks = splitByMonth(working);
    for (const { month, text } of monthChunks) {
      const sentences = splitSentences(text);
      for (const raw of sentences) {
        const sent = tidyText(stripLeadingPunct(raw));
        if (sent.length < 3) continue;
        // Skip OCR fragments that are just 干支/digits (e.g. "丁酉戊午癸未").
        const stripped = sent.replace(/[甲乙丙丁戊己庚辛壬癸子丑寅卯辰巳午未申酉戌亥0-9一二三四五六七八九十、，,。.;；()（）]/g, "");
        if (stripped.length < 2) continue;
        const effectiveMonth = month || fallbackMonth;
        const desc = effectiveMonth ? `${effectiveMonth}，${sent}` : sent;
        out.push(`公元${year}年（${info.reign}${info.reignYearText}年）${desc}。`);
        stats.events++;
      }
    }
    out.push("");
  }

  // Final pass: apply typo fixes to every line. Counts how many lines actually
  // changed so we can report on the cleanup.
  let typoFixCount = 0;
  for (let i = 0; i < out.length; i++) {
    const fixed = applyTypoFixes(out[i]);
    if (fixed !== out[i]) typoFixCount++;
    out[i] = fixed;
  }

  fs.writeFileSync(OUT, out.join("\n"), "utf8");
  console.log(`✓ Wrote ${OUT}`);
  console.log(`  rows parsed: ${stats.rows}, events emitted: ${stats.events}, skipped rows: ${stats.skipped}, hand-overridden years: ${stats.overridden}`);
  console.log(`  typo-fixed lines: ${typoFixCount}`);
  console.log(`  year range: 1350–${lastYear}`);
}

parse();
