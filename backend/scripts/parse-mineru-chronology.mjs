const CN_DIGIT = ["零","一","二","三","四","五","六","七","八","九","十"];
function cnYear(n) {
  if (n === 1) return "元";
  if (n <= 10) return CN_DIGIT[n];
  if (n < 20) return "十" + CN_DIGIT[n - 10];
  if (n === 20) return "二十";
  if (n < 30) return "二十" + CN_DIGIT[n - 20];
  if (n === 30) return "三十";
  if (n < 40) return "三十" + CN_DIGIT[n - 30];
  if (n === 40) return "四十";
  if (n < 50) return "四十" + CN_DIGIT[n - 40];
  return String(n);
}

function reignInfo(year) {
  if (year < 1368) {
    return { reign: "元末", reignYear: year - 1340, reignYearText: cnYear(year - 1340) };
  }
  for (const r of MING_REIGNS) {
    if (year >= r.from && year <= r.to) {
      return { reign: r.reign, reignYear: year - r.from + 1, reignYearText: cnYear(year - r.from + 1) };
    }
  }
  for (const r of SOUTHERN_MING) {
    if (year >= r.from && year <= r.to) {
      return { reign: r.reign, reignYear: year - r.from + 1, reignYearText: cnYear(year - r.from + 1) };
    }
  }
  return { reign: "清初", reignYear: year - 1643, reignYearText: cnYear(year - 1643) };
}

// Strip MinerU artifacts and tidy whitespace.
function clean(s) {
  return s
    .replace(/<br\s*\/?>/g, "")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/\s+/g, "")
    .trim();
}

