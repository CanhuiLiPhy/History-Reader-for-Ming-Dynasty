// Parses the MinerU-OCR'd 大事年表 markdown (HTML tables) into the line-based
// format consumed by timeline-service.js:
//
//   公元YYYY年（<reign><cn-year>年）<event>
//
// Strategy:
//   1. Walk every <tr> in the markdown.
//   2. For each row, pull the 4-digit year out of the first <td> and the
//      longest <td> as the 大事记 column (MinerU sometimes splits per-月
//      cells, sometimes mashes them all into one — this picks the right cell
//      either way).
//   3. Map year → 明 reign + reign-year via a hard-coded table (more reliable
//      than reading the OCR'd dynasty columns).
//   4. Split the 大事记 text into events: first by month tokens (正月/二月/…
//      /十二月/闰X月/是年/是月/是冬/是春/是夏/是秋), then by 。 inside each
//      segment.
//   5. Emit one line per event; keep the month prefix when present.
//
// Pre-1368 rows fall outside Ming reign coverage; we still emit them with
// reign="元末" so the timeline can show the Yuan→Ming transition era.

